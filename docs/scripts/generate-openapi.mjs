// Generates the API reference pages (content/docs/reference/api/**) from docs/openapi.json.
// Runs before `npm run dev` and `npm run build`. The output is gitignored and rebuilt from scratch every
// time, so it always matches the schema, whatever endpoints the server adds or removes.
//
// docs/openapi.json is produced by the server (drf-spectacular). If it is missing, a minimal placeholder is
// written so the docs still build.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateFiles } from 'fumadocs-openapi';
import { createOpenAPI } from 'fumadocs-openapi/server';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaFile = path.join(root, 'openapi.json');
const outDir = path.join(root, 'content/docs/reference/api');

const PLACEHOLDER = {
  openapi: '3.0.3',
  info: {
    title: 'Dialtone API',
    version: '0.0.0',
    description: 'Placeholder. Regenerate docs/openapi.json from the server.',
  },
  paths: {},
};

if (!existsSync(schemaFile)) {
  console.warn('generate-openapi: docs/openapi.json not found, writing a placeholder schema');
  writeFileSync(schemaFile, JSON.stringify(PLACEHOLDER, null, 2) + '\n');
}

let schema;
try {
  schema = JSON.parse(readFileSync(schemaFile, 'utf8'));
} catch (err) {
  console.error(`generate-openapi: docs/openapi.json is not valid JSON: ${err.message}`);
  process.exit(1);
}
const info = schema.info ?? {};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// Group endpoints by the first path segment after /api/ (agents, calls, workflows, ...), whatever tags the
// schema uses. Paths outside /api/ (e.g. /webhook) go under "other".
function groupOf(entry) {
  if (entry.type !== 'operation') return 'webhooks';
  const parts = entry.item.path.split('/').filter(Boolean);
  const i = parts[0] === 'api' ? 1 : 0;
  const seg = parts[i];
  if (!seg || seg.startsWith('{')) return 'other';
  return seg.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
}

const operationCount = Object.values(schema.paths ?? {}).reduce(
  (n, item) =>
    n +
    Object.keys(item ?? {}).filter((k) =>
      ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'].includes(k),
    ).length,
  0,
);

// Operations without a `summary` would be titled after their operationId ("Agents_list"); use
// "GET /api/agents" instead.
function retitle(content) {
  const m = content.match(/operations=\{(\[.*?\])\}/);
  if (!m) return content;
  let ops;
  try {
    ops = JSON.parse(m[1]);
  } catch {
    return content;
  }
  if (ops.length !== 1) return content;
  const { path: opPath, method } = ops[0];
  if (schema.paths?.[opPath]?.[method]?.summary) return content;
  return content.replace(/^title: .*$/m, `title: ${JSON.stringify(`${method.toUpperCase()} ${opPath}`)}`);
}

if (operationCount > 0) {
  await generateFiles({
    input: createOpenAPI({ input: ['./openapi.json'] }),
    output: outDir,
    per: 'operation',
    groupBy: groupOf,
    // Schema descriptions are free text from docstrings; keep them out of MDX so they can't break the build.
    includeDescription: false,
    addGeneratedComment: 'Generated by scripts/generate-openapi.mjs from docs/openapi.json. Do not edit.',
    beforeWrite(files) {
      for (const file of files) file.content = retitle(file.content);
    },
  });
}

// Folder titles for the sidebar.
const title = (s) => s.charAt(0).toUpperCase() + s.slice(1).replace(/-/g, ' ');
const groups = readdirSync(outDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
for (const g of groups) {
  writeFileSync(path.join(outDir, g, 'meta.json'), JSON.stringify({ title: title(g) }, null, 2) + '\n');
}

writeFileSync(
  path.join(outDir, 'meta.json'),
  JSON.stringify({ title: 'API reference', pages: ['index', ...groups] }, null, 2) + '\n',
);

const intro = operationCount
  ? `${operationCount} operations, grouped by resource. Pick one from the sidebar.`
  : 'The schema in `docs/openapi.json` has no operations yet. Regenerate it from the server.';

writeFileSync(
  path.join(outDir, 'index.mdx'),
  `---
title: API reference
description: The server's REST API, generated from its OpenAPI schema.
---

{/* Generated by scripts/generate-openapi.mjs. Do not edit. */}

Schema: **${String(info.title ?? 'Dialtone API').replace(/[{}<>]/g, '')}** version \`${String(info.version ?? '').replace(/[`{}<>]/g, '')}\`. ${intro}

The console is the API's main client. All \`/api/\` endpoints except the agent's runtime ones need a
signed-in session (cookie) and, for writes, the CSRF token from \`GET /api/auth/csrf\`. The server listens on
the host's localhost only (\`DASHBOARD_PORT\`, default 8787); reach it through \`make tunnel\`.

The schema is served live at \`/api/schema/\` and committed as \`docs/openapi.json\`. See
[Architecture](/docs/reference/architecture) for how the pieces call each other.
`,
);

console.log(`generate-openapi: ${operationCount} operations in ${groups.length} groups -> content/docs/reference/api`);
